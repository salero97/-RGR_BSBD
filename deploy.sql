-- блок 11. система временных привилегий (JIT)
CREATE OR REPLACE FUNCTION app.request_temp_privilege(
    p_operation_name TEXT,
    p_duration_min   INTEGER DEFAULT 5,
    p_reason         TEXT DEFAULT NULL
)
RETURNS TABLE (ok BOOLEAN, message TEXT, expires_at TIMESTAMPTZ)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, audit, ref, pg_temp
AS $fn$
DECLARE
    v_role     TEXT := session_user::TEXT;
    v_max_duration integer;
    v_need_reason  boolean;
    v_expires  TIMESTAMPTZ;
    v_request  BIGINT;
BEGIN
    SELECT p.max_duration_min, p.requires_reason
      INTO v_max_duration, v_need_reason
    FROM ref.temp_privilege_policy p
    WHERE p.role_name = v_role
      AND p.operation_name = p_operation_name
      AND p.is_active;

    IF NOT FOUND THEN
        RETURN QUERY SELECT FALSE,
            'Операция ' || p_operation_name || ' не разрешена для роли ' || v_role,
            NULL::TIMESTAMPTZ;
        RETURN;
    END IF;

    IF p_duration_min IS NULL OR p_duration_min < 1 OR p_duration_min > v_max_duration THEN
        RETURN QUERY SELECT FALSE,
            'Длительность должна быть от 1 до ' || v_max_duration || ' минут',
            NULL::TIMESTAMPTZ;
        RETURN;
    END IF;

    IF v_need_reason = true AND COALESCE(btrim(p_reason), '') = '' THEN
        RETURN QUERY SELECT FALSE, 'Не указана причина запроса привилегии', NULL::TIMESTAMPTZ;
        RETURN;
    END IF;

    v_expires := clock_timestamp() + (p_duration_min || ' minutes')::interval;

    INSERT INTO audit.temp_access_log
        (caller_role, operation, expires_at, session_pid, reason)
    VALUES
        (v_role, p_operation_name, v_expires, pg_backend_pid(), p_reason)
    RETURNING request_id INTO v_request;

    PERFORM set_config('app.temp_privilege_until', v_expires::TEXT, false);
    PERFORM set_config('app.temp_privilege_operation', p_operation_name, false);
    PERFORM set_config('app.temp_privilege_request', v_request::TEXT, false);

    RETURN QUERY SELECT TRUE,
        'Привилегия ' || p_operation_name || ' выдана до ' || to_char(v_expires, 'DD.MM.YYYY HH24:MI:SS'),
        v_expires;
END;
$fn$;

CREATE OR REPLACE FUNCTION app.check_temp_privilege(p_operation_name TEXT)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, audit, pg_temp
AS $fn$
DECLARE
    v_until   TIMESTAMPTZ;
    v_op      TEXT;
    v_request BIGINT;
BEGIN
    v_until := NULLIF(current_setting('app.temp_privilege_until', true), '')::TIMESTAMPTZ;
    v_op    := NULLIF(current_setting('app.temp_privilege_operation', true), '');
    v_request := NULLIF(current_setting('app.temp_privilege_request', true), '')::BIGINT;

    IF v_until IS NULL OR v_op IS NULL OR v_request IS NULL THEN
        RETURN FALSE;
    END IF;

    IF v_op <> p_operation_name OR v_until <= clock_timestamp() THEN
        RETURN FALSE;
    END IF;

    RETURN EXISTS (
        SELECT 1
        FROM audit.temp_access_log l
        WHERE l.request_id = v_request
          AND l.caller_role = session_user
          AND l.operation = p_operation_name
          AND l.session_pid = pg_backend_pid()
          AND NOT l.is_revoked
          AND l.expires_at > clock_timestamp()
    );
END;
$fn$;

CREATE OR REPLACE FUNCTION app.reset_temp_privilege()
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, audit, pg_temp
AS $fn$
DECLARE
    v_request BIGINT;
BEGIN
    v_request := NULLIF(current_setting('app.temp_privilege_request', true), '')::BIGINT;

    IF v_request IS NOT NULL THEN
        UPDATE audit.temp_access_log
        SET is_revoked = TRUE, revoked_at = now()
        WHERE request_id = v_request
          AND caller_role = session_user
          AND NOT is_revoked;
    END IF;

    PERFORM set_config('app.temp_privilege_until', '', false);
    PERFORM set_config('app.temp_privilege_operation', '', false);
    PERFORM set_config('app.temp_privilege_request', '', false);
END;
$fn$;

-- блок 12. журнал вызовов функций
CREATE OR REPLACE VIEW audit.v_function_calls
WITH (security_invoker = true) AS
SELECT c.call_id,
       c.call_time,
       c.function_name,
       c.caller_role,
       COALESCE((
           SELECT string_agg(p.param_name || '=' || COALESCE(p.param_value, 'NULL'),
                             ', ' ORDER BY p.param_name)
           FROM audit.function_call_params p
           WHERE p.call_id = c.call_id
       ), '') AS input_params,
       c.success,
       c.error_message
FROM audit.function_calls c;

CREATE OR REPLACE FUNCTION audit.log_function_call(
    p_function_name TEXT,
    p_caller_role   TEXT,
    p_params        JSONB,
    p_success       BOOLEAN,
