CREATE OR REPLACE FUNCTION app.set_session_ctx(p_segment_id INTEGER, p_actor_id INTEGER DEFAULT NULL)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, ref, pg_temp
AS $fn$
BEGIN
    IF p_segment_id IS NULL THEN
        RAISE EXCEPTION 'Не задан идентификатор сегмента' USING ERRCODE = '22004';
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM ref.segment_role sr
        WHERE sr.role_name = session_user
          AND sr.segment_id = p_segment_id
    ) THEN
        RAISE EXCEPTION 'Роль % не имеет прав на сегмент %', session_user, p_segment_id
            USING ERRCODE = '42501';
    END IF;

    PERFORM set_config('app.segment_id', p_segment_id::TEXT, true);

    IF p_actor_id IS NULL THEN
        PERFORM set_config('app.actor_id', '', true);
    ELSE
        PERFORM set_config('app.actor_id', p_actor_id::TEXT, true);
    END IF;
END;
$fn$;

