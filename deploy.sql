-- блок 15. функция резервного копирования журнала
CREATE OR REPLACE FUNCTION audit.backup_audit_logs(p_days_interval INTEGER)
RETURNS TABLE (archived_count BIGINT, deleted_count BIGINT, backup_time TIMESTAMPTZ)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, audit
AS $fn$
DECLARE
    v_cutoff   TIMESTAMPTZ;
    v_archived BIGINT;
    v_deleted  BIGINT;
BEGIN
    IF p_days_interval IS NULL OR p_days_interval <= 0 THEN
        RAISE EXCEPTION 'Интервал должен быть больше 0';
    END IF;

    v_cutoff := now() - (p_days_interval || ' days')::interval;

    INSERT INTO audit.row_change_log_archive
        (change_id, change_time, table_name, operation, changed_by,
         segment_id, row_pk, old_data, new_data)
    SELECT change_id, change_time, table_name, operation, changed_by,
           segment_id, row_pk, old_data, new_data
    FROM audit.row_change_log
    WHERE change_time < v_cutoff;

    GET DIAGNOSTICS v_archived = ROW_COUNT;

    DELETE FROM audit.row_change_log
    WHERE change_time < v_cutoff;

    GET DIAGNOSTICS v_deleted = ROW_COUNT;

    IF v_archived <> v_deleted THEN
        RAISE EXCEPTION 'Количество архивированных и удаленных записей не совпадает';
    END IF;

    RETURN QUERY SELECT v_archived, v_deleted, now();
END;
$fn$;

-- блок 16. безопасные представления
CREATE OR REPLACE VIEW app.v_students_safe
WITH (security_invoker = true) AS
SELECT student_id, segment_id, group_id, last_name, first_name, middle_name, status
FROM app.students
WHERE segment_id = app.current_segment_id()
WITH CHECK OPTION;

CREATE OR REPLACE VIEW app.v_grades_safe
WITH (security_invoker = true) AS
SELECT grade_id, segment_id, student_id, discipline_id, grade_value, grade_date
FROM app.grades
WHERE segment_id = app.current_segment_id()
WITH CHECK OPTION;

CREATE OR REPLACE VIEW app.v_grades_aggregate
WITH (security_barrier = true, security_invoker = true) AS
SELECT segment_id, discipline_id,
       count(*) AS grades_count,
       round(avg(grade_value), 2) AS avg_grade,
       min(grade_value) AS min_grade,
       max(grade_value) AS max_grade
FROM app.grades
GROUP BY segment_id, discipline_id;

CREATE OR REPLACE VIEW app.v_students_count
WITH (security_barrier = true, security_invoker = true) AS
SELECT segment_id, group_id, count(*) AS students_count
FROM app.students
GROUP BY segment_id, group_id;


