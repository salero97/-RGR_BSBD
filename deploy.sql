-- блок 14. аудит изменений и регистрация подключений
CREATE OR REPLACE FUNCTION audit.log_row_change()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, audit
AS $fn$
DECLARE
    v_old JSONB;
    v_new JSONB;
    v_src JSONB;
    v_pk  JSONB;
    v_segment INTEGER;
BEGIN
    IF TG_OP IN ('UPDATE','DELETE') THEN
        v_old := to_jsonb(OLD);
    END IF;

    IF TG_OP IN ('INSERT','UPDATE') THEN
        v_new := to_jsonb(NEW);
    END IF;

    v_src := COALESCE(v_new, v_old);

    IF TG_TABLE_NAME = 'personal_files' THEN
        IF v_old IS NOT NULL THEN
            v_old := v_old || '{"passport_number":"***","snils":"***","phone":"***","address":"***"}'::JSONB;
        END IF;
        IF v_new IS NOT NULL THEN
            v_new := v_new || '{"passport_number":"***","snils":"***","phone":"***","address":"***"}'::JSONB;
        END IF;
    END IF;

    IF TG_TABLE_NAME = 'teacher_personal_files' THEN
        IF v_old IS NOT NULL THEN
            v_old := v_old || '{"passport_number":"***","snils":"***","phone":"***","address":"***"}'::JSONB;
        END IF;
        IF v_new IS NOT NULL THEN
            v_new := v_new || '{"passport_number":"***","snils":"***","phone":"***","address":"***"}'::JSONB;
        END IF;
    END IF;

    IF TG_TABLE_NAME = 'students' THEN
        IF v_old IS NOT NULL AND v_old ->> 'email' IS NOT NULL THEN
            v_old := v_old || jsonb_build_object('email', md5(v_old ->> 'email'));
        END IF;
        IF v_new IS NOT NULL AND v_new ->> 'email' IS NOT NULL THEN
            v_new := v_new || jsonb_build_object('email', md5(v_new ->> 'email'));
        END IF;
    END IF;

    v_segment := (v_src ->> 'segment_id')::INTEGER;

    IF TG_TABLE_NAME = 'students' THEN
        v_pk := jsonb_build_object('student_id', v_src -> 'student_id');
    ELSIF TG_TABLE_NAME = 'grades' THEN
        v_pk := jsonb_build_object('grade_id', v_src -> 'grade_id');
    ELSE
        v_pk := jsonb_build_object('file_id', v_src -> 'file_id');
    END IF;

    INSERT INTO audit.row_change_log (table_name, operation, segment_id, row_pk, old_data, new_data)
    VALUES (TG_TABLE_SCHEMA || '.' || TG_TABLE_NAME, lower(TG_OP), v_segment, v_pk, v_old, v_new);

    RETURN NULL;
END;
$fn$;

