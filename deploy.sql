CREATE OR REPLACE FUNCTION app.sp_add_grade(
    p_student_id    INTEGER,
    p_discipline_id INTEGER,
    p_teacher_id    INTEGER,
    p_grade_value   INTEGER,
    p_grade_date    DATE
)
RETURNS TABLE (ok BOOLEAN, message TEXT, result_id BIGINT)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, app, ref, audit, pg_temp
AS $fn$
DECLARE
    v_segment INTEGER;
    v_id      BIGINT;
    v_params  JSONB;
BEGIN
    v_params := jsonb_build_object(
        'student_id', p_student_id, 'discipline_id', p_discipline_id,
        'teacher_id', p_teacher_id, 'grade_value', p_grade_value,
        'grade_date', p_grade_date);

    v_segment := app.get_checked_segment();

    IF v_segment IS NULL THEN
        PERFORM audit.log_function_call('app.sp_add_grade', session_user::TEXT, v_params, FALSE,
                                        'Контекст сегмента не задан');
        RETURN QUERY SELECT FALSE, 'Контекст сегмента не задан'::TEXT, NULL::BIGINT;
        RETURN;
    END IF;

    IF p_grade_value IS NULL OR p_grade_value NOT BETWEEN 2 AND 5 THEN
        PERFORM audit.log_function_call('app.sp_add_grade', session_user::TEXT, v_params, FALSE,
                                        'Оценка вне диапазона 2..5');
        RETURN QUERY SELECT FALSE, 'Оценка должна быть в диапазоне от 2 до 5'::TEXT, NULL::BIGINT;
        RETURN;
    END IF;

    IF p_grade_date IS NULL OR p_grade_date > current_date OR p_grade_date < DATE '2000-01-01' THEN
        PERFORM audit.log_function_call('app.sp_add_grade', session_user::TEXT, v_params, FALSE,
                                        'Недопустимая дата оценки');
        RETURN QUERY SELECT FALSE, 'Дата оценки вне допустимого диапазона'::TEXT, NULL::BIGINT;
        RETURN;
    END IF;

    IF NOT EXISTS (SELECT 1 FROM app.students s
                   WHERE s.student_id = p_student_id AND s.segment_id = v_segment) THEN
        PERFORM audit.log_function_call('app.sp_add_grade', session_user::TEXT, v_params, FALSE,
                                        'Студент не найден в сегменте');
        RETURN QUERY SELECT FALSE, 'Студент ' || p_student_id || ' не найден в сегменте', NULL::BIGINT;
        RETURN;
    END IF;

    IF NOT EXISTS (SELECT 1 FROM app.teachers t
                   WHERE t.teacher_id = p_teacher_id AND t.segment_id = v_segment) THEN
        PERFORM audit.log_function_call('app.sp_add_grade', session_user::TEXT, v_params, FALSE,
                                        'Преподаватель не найден в сегменте');
        RETURN QUERY SELECT FALSE, 'Преподаватель ' || p_teacher_id || ' не найден в сегменте', NULL::BIGINT;
        RETURN;
    END IF;

    IF NOT EXISTS (SELECT 1 FROM app.enrollments e
                   WHERE e.student_id = p_student_id AND e.discipline_id = p_discipline_id) THEN
        PERFORM audit.log_function_call('app.sp_add_grade', session_user::TEXT, v_params, FALSE,
                                        'Студент не записан на дисциплину');
        RETURN QUERY SELECT FALSE, 'Студент ' || p_student_id || ' не записан на дисциплину ' || p_discipline_id, NULL::BIGINT;
        RETURN;
    END IF;

    IF NOT EXISTS (SELECT 1 FROM app.teacher_discipline td
                   WHERE td.teacher_id = p_teacher_id AND td.discipline_id = p_discipline_id) THEN
        PERFORM audit.log_function_call('app.sp_add_grade', session_user::TEXT, v_params, FALSE,
                                        'Дисциплина не закреплена за преподавателем');
        RETURN QUERY SELECT FALSE, 'Дисциплина ' || p_discipline_id || ' не закреплена за преподавателем ' || p_teacher_id, NULL::BIGINT;
        RETURN;
    END IF;

    IF EXISTS (SELECT 1 FROM app.grades g
               WHERE g.student_id = p_student_id
                 AND g.discipline_id = p_discipline_id
                 AND g.grade_date = p_grade_date) THEN
        PERFORM audit.log_function_call('app.sp_add_grade', session_user::TEXT, v_params, FALSE,
                                        'Дубликат оценки');
        RETURN QUERY SELECT FALSE, 'Оценка за эту дату уже выставлена'::TEXT, NULL::BIGINT;
        RETURN;
    END IF;

    INSERT INTO app.grades (student_id, discipline_id, teacher_id, grade_value, grade_date, segment_id)
    VALUES (p_student_id, p_discipline_id, p_teacher_id, p_grade_value, p_grade_date, v_segment)
    RETURNING grade_id INTO v_id;

    PERFORM audit.log_function_call('app.sp_add_grade', session_user::TEXT, v_params, TRUE, NULL);

    RETURN QUERY SELECT TRUE, 'Оценка зарегистрирована'::TEXT, v_id;
END;
$fn$;

CREATE OR REPLACE FUNCTION app.sp_register_student(
    p_last_name   VARCHAR,
    p_first_name  VARCHAR,
    p_middle_name VARCHAR,
    p_birth_date  DATE,
    p_email       VARCHAR,
    p_group_id    INTEGER,
    p_status      VARCHAR
)
RETURNS TABLE (ok BOOLEAN, message TEXT, result_id BIGINT)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, app, ref, audit, pg_temp
AS $fn$
DECLARE
    v_segment INTEGER;
    v_id      BIGINT;
    v_params  JSONB;
    v_last    TEXT := btrim(p_last_name);
    v_first   TEXT := btrim(p_first_name);
    v_middle  TEXT := nullif(btrim(p_middle_name), '');
    v_email   TEXT := nullif(btrim(p_email), '');
BEGIN
    v_params := jsonb_build_object(
        'last_name', p_last_name, 'first_name', p_first_name,
        'middle_name', p_middle_name, 'birth_date', p_birth_date,
        'email', p_email, 'group_id', p_group_id, 'status', p_status);

    v_segment := app.get_checked_segment();

    IF v_segment IS NULL THEN
        PERFORM audit.log_function_call('app.sp_register_student', session_user::TEXT, v_params, FALSE,
                                        'Контекст сегмента не задан');
        RETURN QUERY SELECT FALSE, 'Контекст сегмента не задан'::TEXT, NULL::BIGINT;
        RETURN;
    END IF;

    IF COALESCE(v_last, '') = '' OR COALESCE(v_first, '') = '' OR p_birth_date IS NULL
       OR p_group_id IS NULL OR COALESCE(btrim(p_status), '') = '' THEN
        PERFORM audit.log_function_call('app.sp_register_student', session_user::TEXT, v_params, FALSE,
                                        'Не заданы обязательные параметры');
        RETURN QUERY SELECT FALSE, 'Не заданы обязательные параметры'::TEXT, NULL::BIGINT;
        RETURN;
    END IF;

    IF v_last !~ '^[А-ЯЁ][а-яё-]+$' OR v_first !~ '^[А-ЯЁ][а-яё-]+$' THEN
        PERFORM audit.log_function_call('app.sp_register_student', session_user::TEXT, v_params, FALSE,
                                        'Некорректный формат имени');
        RETURN QUERY SELECT FALSE, 'Фамилия и имя записываются кириллицей с заглавной буквы'::TEXT, NULL::BIGINT;
        RETURN;
    END IF;

    IF p_birth_date > current_date - INTERVAL '14 years'
       OR p_birth_date < DATE '1950-01-01' THEN
        PERFORM audit.log_function_call('app.sp_register_student', session_user::TEXT, v_params, FALSE,
                                        'Недопустимая дата рождения');
        RETURN QUERY SELECT FALSE, 'Возраст студента не менее 14 лет, год рождения не раньше 1950'::TEXT, NULL::BIGINT;
        RETURN;
    END IF;

    IF v_email IS NOT NULL AND v_email !~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]{2,}$' THEN
        PERFORM audit.log_function_call('app.sp_register_student', session_user::TEXT, v_params, FALSE,
                                        'Некорректный адрес электронной почты');
        RETURN QUERY SELECT FALSE, 'Формат адреса электронной почты "' || v_email || '" некорректен',
                            NULL::BIGINT;
        RETURN;
    END IF;

    IF NOT EXISTS (SELECT 1 FROM app.groups g
                   WHERE g.group_id = p_group_id AND g.segment_id = v_segment) THEN
        PERFORM audit.log_function_call('app.sp_register_student', session_user::TEXT, v_params, FALSE,
                                        'Группа не найдена в сегменте');
        RETURN QUERY SELECT FALSE, 'Группа ' || p_group_id || ' не найдена в сегменте', NULL::BIGINT;
        RETURN;
    END IF;

    IF v_email IS NOT NULL AND EXISTS (
        SELECT 1 FROM app.students s WHERE lower(s.email) = lower(v_email)) THEN
        PERFORM audit.log_function_call('app.sp_register_student', session_user::TEXT, v_params, FALSE,
                                        'Адрес электронной почты занят');
        RETURN QUERY SELECT FALSE, 'Адрес электронной почты "' || v_email || '" уже занят', NULL::BIGINT;
        RETURN;
    END IF;

    INSERT INTO app.students (group_id, birth_date, email, status, last_name, first_name, middle_name, segment_id)
    VALUES (p_group_id, p_birth_date, v_email, p_status, v_last, v_first, v_middle, v_segment)
    RETURNING student_id INTO v_id;

    PERFORM audit.log_function_call('app.sp_register_student', session_user::TEXT, v_params, TRUE, NULL);

    RETURN QUERY SELECT TRUE, 'Студент зарегистрирован'::TEXT, v_id;
EXCEPTION
    WHEN check_violation THEN
        PERFORM audit.log_function_call('app.sp_register_student', session_user::TEXT, v_params, FALSE,
                                        SQLERRM);
        RETURN QUERY SELECT FALSE, 'Нарушено ограничение таблицы: ' || SQLERRM, NULL::BIGINT;
END;
$fn$;

CREATE OR REPLACE FUNCTION app.sp_transfer_student(
    p_student_id INTEGER,
    p_new_group_id INTEGER
)
RETURNS TABLE (ok BOOLEAN, message TEXT, result_id BIGINT)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, app, ref, audit, pg_temp
AS $fn$
DECLARE
    v_segment   INTEGER;
    v_old_group INTEGER;
    v_old_year  SMALLINT;
    v_new_year  SMALLINT;
    v_params    JSONB;
BEGIN
    v_params := jsonb_build_object('student_id', p_student_id, 'new_group_id', p_new_group_id);

    v_segment := app.get_checked_segment();

    IF v_segment IS NULL THEN
        PERFORM audit.log_function_call('app.sp_transfer_student', session_user::TEXT, v_params, FALSE,
                                        'Контекст сегмента не задан');
        RETURN QUERY SELECT FALSE, 'Контекст сегмента не задан'::TEXT, NULL::BIGINT;
        RETURN;
    END IF;

    SELECT s.group_id INTO v_old_group
    FROM app.students s
    WHERE s.student_id = p_student_id AND s.segment_id = v_segment
    FOR UPDATE;

    IF NOT FOUND THEN
        PERFORM audit.log_function_call('app.sp_transfer_student', session_user::TEXT, v_params, FALSE,
                                        'Студент не найден в сегменте');
        RETURN QUERY SELECT FALSE, 'Студент ' || p_student_id || ' не найден в сегменте', NULL::BIGINT;
        RETURN;
    END IF;

    IF v_old_group = p_new_group_id THEN
        PERFORM audit.log_function_call('app.sp_transfer_student', session_user::TEXT, v_params, FALSE,
                                        'Новая группа совпадает с текущей');
        RETURN QUERY SELECT FALSE, 'Новая группа совпадает с текущей'::TEXT, NULL::BIGINT;
        RETURN;
    END IF;

    SELECT g.year_of_admission INTO v_old_year
    FROM app.groups g WHERE g.group_id = v_old_group;

    SELECT g.year_of_admission INTO v_new_year
    FROM app.groups g
    WHERE g.group_id = p_new_group_id AND g.segment_id = v_segment;

    IF v_new_year IS NULL THEN
        PERFORM audit.log_function_call('app.sp_transfer_student', session_user::TEXT, v_params, FALSE,
                                        'Новая группа не найдена в сегменте');
        RETURN QUERY SELECT FALSE, 'Группа ' || p_new_group_id || ' не найдена в сегменте', NULL::BIGINT;
        RETURN;
    END IF;

    IF v_old_year <> v_new_year THEN
        PERFORM audit.log_function_call('app.sp_transfer_student', session_user::TEXT, v_params, FALSE,
                                        'Разный год поступления групп');
        RETURN QUERY SELECT FALSE, 'Перевод между группами с разным годом поступления запрещен: ' || v_old_year || ' и ' || v_new_year, NULL::BIGINT;
        RETURN;
    END IF;

    UPDATE app.students
    SET group_id = p_new_group_id
    WHERE student_id = p_student_id AND segment_id = v_segment;

    PERFORM audit.log_function_call('app.sp_transfer_student', session_user::TEXT, v_params, TRUE, NULL);

    RETURN QUERY SELECT TRUE, 'Студент переведен в новую группу'::TEXT, p_student_id::BIGINT;
END;
$fn$;

CREATE OR REPLACE FUNCTION app.sp_delete_student(p_student_id INTEGER)
RETURNS TABLE (ok BOOLEAN, message TEXT, deleted_rows BIGINT)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, app, audit, pg_temp
AS $fn$
DECLARE
    v_segment INTEGER;
    v_count   BIGINT;
    v_params  JSONB := jsonb_build_object('student_id', p_student_id);
BEGIN
    v_segment := app.get_checked_segment();

    IF v_segment IS NULL THEN
        PERFORM audit.log_function_call('app.sp_delete_student', session_user::TEXT, v_params, FALSE,
                                        'Контекст сегмента не задан');
        RETURN QUERY SELECT FALSE, 'Контекст сегмента не задан'::TEXT, 0::BIGINT;
        RETURN;
    END IF;

    IF NOT app.check_temp_privilege('delete_student') THEN
        PERFORM audit.log_function_call('app.sp_delete_student', session_user::TEXT, v_params, FALSE,
                                        'Временная привилегия отсутствует или истекла');
