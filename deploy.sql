        PERFORM audit.log_function_call('app.sp_delete_student', session_user::TEXT, v_params, FALSE,
                                        'Студент не найден в сегменте');
        RETURN QUERY SELECT FALSE, 'Студент ' || p_student_id || ' не найден в сегменте', 0::BIGINT;
        RETURN;
    END IF;

    PERFORM audit.log_function_call('app.sp_delete_student', session_user::TEXT, v_params, TRUE, NULL);

    RETURN QUERY SELECT TRUE, 'Студент удален'::TEXT, v_count;
END;
