-- блок 20. проверка развертывания
SELECT 'схемы' AS показатель, count(*)::text AS значение
FROM pg_namespace WHERE nspname IN ('app','ref','audit','stg')
UNION ALL
SELECT 'таблицы', count(*)::text FROM pg_tables
WHERE schemaname IN ('app','ref','audit','stg')
UNION ALL
SELECT 'функции security definer', count(*)::text FROM pg_proc p
JOIN pg_namespace n ON n.oid = p.pronamespace
WHERE n.nspname IN ('app','audit') AND p.prosecdef
UNION ALL
SELECT 'политики rls', count(*)::text FROM pg_policies WHERE schemaname = 'app'
UNION ALL
SELECT 'триггеры аудита', count(*)::text FROM pg_trigger WHERE NOT tgisinternal AND tgname LIKE 'trg_%'
UNION ALL
SELECT 'функция ' || p.proname,
       pg_get_userbyid(p.proowner) || ', search_path: ' ||
       coalesce(array_to_string(p.proconfig, ', '), 'не задан')
FROM pg_proc p
JOIN pg_namespace n ON n.oid = p.pronamespace
WHERE n.nspname IN ('app','audit') AND p.prosecdef
ORDER BY 1;
