            'Операция отклонена: нет действующей временной привилегии delete_student'::TEXT,
            0::BIGINT;
        RETURN;
    END IF;

    DELETE FROM app.students
    WHERE student_id = p_student_id AND segment_id = v_segment;

    GET DIAGNOSTICS v_count = ROW_COUNT;

